export function useContinuityText() {
  const { locale } = useI18n()
  const ct = (key: keyof typeof messages.zh | string, params: Record<string, unknown> = {}) => {
    const catalog = locale.value === 'zh' ? messages.zh : messages.en
    const text = taskMessages[locale.value]?.[key] || catalog[key as keyof typeof messages.zh] || key
    return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''))
  }
  return { ct }
}
